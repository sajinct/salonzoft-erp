// Stamps the build identity before `ng build` (run in CI from apps/web):
//  * src/environments/version.ts  — version (package.json), short commit, build time
//  * ngsw-config.json appData       — the same, so update events can name the new version
// Every deploy therefore changes the bundle hash, and installed apps pick it up.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
let commit = (process.env.GITHUB_SHA ?? '').slice(0, 7);
if (!commit) {
  try {
    commit = execSync('git rev-parse --short=7 HEAD').toString().trim();
  } catch {
    commit = 'local';
  }
}
const builtAt = new Date().toISOString();
const identity = { version: pkg.version, commit, builtAt };

writeFileSync(
  'src/environments/version.ts',
  `// Generated by scripts/stamp-version.mjs — do not edit.\nexport const APP_VERSION = ${JSON.stringify(identity, null, 2)};\n`,
);

const ngsw = JSON.parse(readFileSync('ngsw-config.json', 'utf8'));
ngsw.appData = identity;
writeFileSync('ngsw-config.json', JSON.stringify(ngsw, null, 2) + '\n');

console.log(`Salonzoft ${pkg.version} (${commit}) ${builtAt}`);
